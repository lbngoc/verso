//! macOS pasteboard snapshot/restore (clean-room from the PasteboardSnapshot idea).
//!
//! Every item and type is captured in order, `*promise*` types are skipped (they are produced on
//! demand and cannot be replayed), and size caps keep a copied photo from ballooning memory
//! (16 MB per type, 64 MB total). Restore marks both items and the pasteboard so clipboard
//! managers ignore it (FR-003, research P4).

use log::debug;
use objc2::msg_send;
use objc2::rc::Retained;
use objc2_app_kit::{NSPasteboard, NSPasteboardItem};
use objc2_foundation::{NSArray, NSData, NSString};

use crate::platform::ClipboardState;

pub const MAX_TYPE_BYTES: usize = 16 * 1024 * 1024;
pub const MAX_TOTAL_BYTES: usize = 64 * 1024 * 1024;

const TRANSIENT_TYPE: &str = "org.nspasteboard.TransientType";
const AUTO_GENERATED_TYPE: &str = "org.nspasteboard.AutoGeneratedType";

struct SnapshotItem {
    types: Vec<(Retained<NSString>, Retained<NSData>)>,
}

pub struct PasteboardSnapshot {
    change_count: isize,
    items: Vec<SnapshotItem>,
    pub skipped_formats: Vec<String>,
}

pub struct RestoreReport {
    pub state: ClipboardState,
    pub skipped_formats: Vec<String>,
}

impl PasteboardSnapshot {
    /// Captures the general pasteboard without modifying it.
    pub fn capture() -> Option<Self> {
        let pasteboard = NSPasteboard::generalPasteboard();
        let change_count = pasteboard.changeCount();
        let items = pasteboard
            .pasteboardItems()
            .unwrap_or_else(|| NSArray::<NSPasteboardItem>::from_retained_slice(&[]));

        let mut snapshot_items = Vec::new();
        let mut skipped_formats = Vec::new();
        let mut total: usize = 0;

        for item in items.iter() {
            let mut stored = Vec::new();
            {
                let types = item.types();
                for data_type in types.iter() {
                    let name = data_type.to_string();
                    if name.contains("promise") {
                        skipped_formats.push(name);
                        continue;
                    }
                    if let Some(data) = item.dataForType(&data_type) {
                        let length = data.length();
                        if length > MAX_TYPE_BYTES || total + length > MAX_TOTAL_BYTES {
                            skipped_formats.push(name);
                            continue;
                        }
                        total += length;
                        stored.push((data_type.clone(), data));
                    }
                }
            }
            snapshot_items.push(SnapshotItem { types: stored });
        }

        Some(Self {
            change_count,
            items: snapshot_items,
            skipped_formats,
        })
    }

    pub fn change_count(&self) -> isize {
        self.change_count
    }

    /// Writes the snapshot back, marking it as transient. Callers pass the pasteboard's current
    /// change count so an untouched clipboard is never rewritten.
    pub fn restore(self, current_change_count: isize) -> RestoreReport {
        if current_change_count == self.change_count {
            return RestoreReport {
                state: ClipboardState::Untouched,
                skipped_formats: Vec::new(),
            };
        }

        let pasteboard = NSPasteboard::generalPasteboard();
        pasteboard.clearContents();

        let mut objects: Vec<Retained<NSPasteboardItem>> = Vec::new();
        for item in &self.items {
            let pasteboard_item = NSPasteboardItem::new();
            for (data_type, data) in &item.types {
                let _ = pasteboard_item.setData_forType(data, data_type);
            }
            mark_transient(&pasteboard_item);
            objects.push(pasteboard_item);
        }

        let array = NSArray::from_retained_slice(&objects);
        let written: bool = unsafe { msg_send![&*pasteboard, writeObjects: &*array] };
        debug!(
            "pasteboard restore wrote {} items: {written}",
            objects.len()
        );

        let state = if self.skipped_formats.is_empty() {
            ClipboardState::Restored
        } else {
            ClipboardState::PartiallyRestored
        };
        RestoreReport {
            state,
            skipped_formats: self.skipped_formats,
        }
    }
}

fn mark_transient(item: &NSPasteboardItem) {
    let marker = NSString::from_str("1");
    for name in [TRANSIENT_TYPE, AUTO_GENERATED_TYPE] {
        let data_type = NSString::from_str(name);
        item.setString_forType(&marker, &data_type);
    }
}

/// Reads the plain-text representation currently on the pasteboard (the copy fallback's answer).
pub fn read_text() -> Option<String> {
    let pasteboard = NSPasteboard::generalPasteboard();
    let data_type = NSString::from_str("public.utf8-plain-text");
    pasteboard
        .stringForType(&data_type)
        .map(|value| value.to_string())
}

pub fn change_count() -> isize {
    NSPasteboard::generalPasteboard().changeCount()
}

/// Replaces the general pasteboard with one plain-text item ("Copy diagnostics").
pub fn write_text(text: &str) -> Result<(), String> {
    let pasteboard = NSPasteboard::generalPasteboard();
    pasteboard.clearContents();
    let value = NSString::from_str(text);
    let uti = NSString::from_str("public.utf8-plain-text");
    if pasteboard.setString_forType(&value, &uti) {
        Ok(())
    } else {
        Err("the pasteboard refused the text".into())
    }
}
